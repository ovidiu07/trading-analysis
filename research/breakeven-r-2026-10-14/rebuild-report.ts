import { readFileSync, writeFileSync } from 'node:fs'
import assert from 'node:assert/strict'
import { buildBacktestingReport, reportArchive } from '../../frontend/src/features/backtesting/export'
import { computeResearchMetrics } from '../../frontend/src/features/backtesting/research'
import type { BacktestingTrade, BacktestingWorkspace } from '../../frontend/src/api/backtesting'

// Local report regeneration using the production export functions, without application or database access.
const dir = new URL('.', import.meta.url)
const out = new URL('../../output/breakeven-r-2026-10-14/', dir)
const { trades, metadata, changes } = JSON.parse(readFileSync(new URL('source.json', dir), 'utf8')) as {
  trades: BacktestingTrade[]
  metadata: { workspace: BacktestingWorkspace; period: { from: string; to: string; dateBasis: 'entry' }; generatedAt: string }
  changes: unknown[]
}
const metrics = computeResearchMetrics(trades)
assert.equal(trades.length, 523)
assert.equal(changes.length, 20)
assert.equal(metrics.totalR, 67)
assert.equal(metrics.currencyMetrics?.USD.netPnl, 6515.36)
assert.equal(metrics.wins, 158)
assert.equal(metrics.losses, 365)
assert.equal(metrics.breakevens, 0)
const files = buildBacktestingReport(metadata.workspace, trades, metadata.period, [], [])
const generatedMetadata = JSON.parse(files['workspace.json'])
generatedMetadata.correction = {
  method: 'FIXED_OUTCOME_RR_TIMES_LOCK_PERCENT', changedTrades: 20,
  beforeR: 109, correctedModelR: 67, exactExpectancyR: 67 / 523,
  originalGeneratedAt: metadata.generatedAt, deployedDatabaseModified: false,
  measuredFillPriceR: 'UNAVAILABLE_ORIGINAL_STOP_AND_TARGET_NOT_EXPORTED',
}
// Retain the historical workspace snapshot with its original scope; prevent confusing it with corrected analytics.
generatedMetadata.workspaceStatisticsScope = 'ORIGINAL_UNCORRECTED_ALL_TIME_SNAPSHOT_SEE_CORRECTED_OVERVIEW'
files['workspace.json'] = JSON.stringify(generatedMetadata, null, 2) + '\n'
files['README.txt'] = [
  'LOCAL CORRECTED COPY: 20 BE exits changed from +3R to +0.9R under the declared fixed outcome model.',
  'Corrected model total: +67R; exact expectancy: 67/523 = 0.1281070746R per trade.',
  'This is an approximation from planned R:R 3 and source protected profit 30%, not measured fill-price R.',
  'Original initial stop and target prices are absent; tick rounding, improved fills, gaps and costs can change measured R.',
  'Cash remains $6,515.36. BE names the protected exit order; the 20 profitable BE exits remain cash WIN outcomes.',
  'Trade IDs, planned R:R, execution fields, notes, tags and all non-R trade fields are preserved.',
  'All selected-period analytics are regenerated by the production export functions.',
  'workspace.json retains the original uncorrected historical workspace snapshot, explicitly labeled as such.',
  'Original source files and deployed application data are unchanged. See be-r-audit.json for source hash and changed IDs.',
  '', files['README.txt'],
].join('\r\n')
files['be-r-audit.json'] = readFileSync(new URL('be-r-audit.json', out), 'utf8')
for (const [name, contents] of Object.entries(files)) writeFileSync(new URL(name, out), contents)
writeFileSync(new URL('v2-corrected-fixed-model-report.zip', out), reportArchive(files))
console.log(JSON.stringify({ trades: trades.length, changed: changes.length, totalR: metrics.totalR,
  exactExpectancyR: 67 / 523, profitFactorR: metrics.profitFactor, drawdownR: metrics.maximumDrawdownR,
  cashUSD: metrics.currencyMetrics?.USD.netPnl, archive: new URL('v2-corrected-fixed-model-report.zip', out).pathname }))
